/** Advance per letter, in grid units (letter 4 wide + 1 space). */
export const ADV = 5;
/** Width of a line of text at cap height h (mm). */
export const textWidth = (s: string, h: number) => Math.max(0, s.length * ADV - 1) * h / 6;
/**
 * The text as open line shapes, cap height h mm, its baseline-left at `at`,
 * turned by `angle` radians.
 */
export function strokeText(s: string, h: number, at: Point = P(0, 0), angle = 0): Shape[] {
  const k = h / 6, c = Math.cos(angle), sn = Math.sin(angle), out: Shape[] = [];
  [...s.toUpperCase()].forEach((ch, i) => {
    const g = GLYPHS[ch] ?? GLYPHS['?'];
    for (const stroke of g) {
      const pts = stroke.map(([x, y]) => { const lx = (i * ADV + x) * k, ly = y * k; return P(at.x + lx * c - ly * sn, at.y + lx * sn + ly * c); });
      out.push(pts.length === 2 ? { type: 'line', a: pts[0], b: pts[1] } as Shape : { type: 'poly', closed: false, pts } as Shape);
    }
  });
  return out;
}
